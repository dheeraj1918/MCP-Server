"""
Task planner — breaks the user's objective into Wave-1 + Wave-2 tasks.

Wave-1 tasks: Code Generator, research, analysis (independent)
Wave-2 tasks: GitHub Publisher, deployer (depend on Wave-1 output)

The planner always ensures that GitHub-related requests produce:
  - At least one Code Generator task (Wave-1)
  - Exactly one GitHub Publisher task (Wave-2) with role "GitHub Publisher"
"""

import json
import logging
import re
from typing import Any

from backend.config import MAX_AGENTS
from backend.services.mcp_client import send_to_mcp

logger = logging.getLogger(__name__)


# ── helpers ───────────────────────────────────────────────────────────────────

def _fallback_plan(prompt: str) -> dict[str, Any]:
    return {
        "complexity": "simple",
        "tasks": [{
            "name": "worker_1",
            "role": "General assistant",
            "type": "general",
            "task": prompt,
        }],
    }


def _extract_json(raw: Any) -> dict[str, Any]:
    if isinstance(raw, dict):
        return raw
    text = str(raw).strip()
    if text.startswith("```"):
        lines = text.splitlines()[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines).strip()
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end <= start:
        raise ValueError(f"No JSON object found: {text[:200]!r}")
    try:
        return json.loads(text[start:end + 1])
    except json.JSONDecodeError as exc:
        raise ValueError(f"Malformed JSON: {exc}") from exc


def _extract_repo_name(prompt: str, tasks: list[dict]) -> str:
    """Try to pull a repo name from the prompt or task text."""
    STOPWORDS = {"named", "called", "a", "an", "the", "my", "your", "new", "into", "it"}
    for text in [prompt] + [t.get("task", "") for t in tasks]:
        m = re.search(
            r"(?:repo(?:sitory)?)\s+(?:named?|called?)\s+['\"]?([^\s'\",.]+)['\"]?",
            text, re.IGNORECASE,
        )
        if m:
            c = m.group(1).lower().replace("_", "-").strip("\"'.,")
            if c and c not in STOPWORDS:
                return c
        m = re.search(r"['\"]([a-z0-9][a-z0-9_\-]{1,38})['\"]", text, re.IGNORECASE)
        if m:
            c = m.group(1).lower().replace("_", "-")
            if c not in STOPWORDS:
                return c
    return ""


def _make_publisher_task(n: int, repo_name: str, prompt: str) -> dict:
    """Build a canonical GitHub Publisher task that always hits _is_dependent."""
    repo_clause = f" named '{repo_name}'" if repo_name else ""
    return {
        "name": f"worker_{n}",
        "role": "GitHub Publisher",    # matches _DEPENDENT_ROLE_WORDS
        "type": "general",
        "task": (
            f"Create a GitHub repository{repo_clause} and "
            "push all files generated by the Code Generator to GitHub. "    # matches _DEPENDENT_TASK_WORDS
            "Steps: call github_whoami, then github_create_repo with confirm=true, "
            "then github_push_files with confirm=true."
        ),
    }


# ── main planner ──────────────────────────────────────────────────────────────

async def plan_tasks(prompt: str) -> dict[str, Any]:
    planning_prompt = f"""You are the task planner for Factory OS.
Break the user's objective into {MAX_AGENTS} or fewer tasks.

RULES:
- type "retrieval" — read-only data fetching (web search, list GitHub repos, read files).
- type "general"   — everything else: writing code, creating files, GitHub operations, APIs.

COMPLEXITY:
- "simple"   — one task.
- "moderate" — 2-3 tasks.
- "complex"  — up to {MAX_AGENTS} tasks.

FOR REQUESTS THAT INVOLVE CODE + GITHUB:
  Task 1: role="Code Generator", type="general"
          task="Write all code files for <project name>. Include README.md."
  Task 2: role="GitHub Publisher", type="general"
          task="Create a GitHub repository named '<repo-name>' and push all files
                generated by the Code Generator to GitHub."

Return ONLY valid JSON — no markdown, no explanation:
{{"complexity":"simple|moderate|complex","tasks":[{{"name":"worker_1","role":"<role>","type":"general|retrieval","task":"<task>"}}]}}

User objective: {prompt}
"""
    try:
        response = await send_to_mcp(planning_prompt)
        raw = response.get("response", "")

        try:
            data = _extract_json(raw)
        except ValueError as e:
            logger.warning("Planner JSON parse failed: %s", e)
            fb = _fallback_plan(prompt)
            fb["planning_error"] = str(e)
            return fb

        raw_tasks = data.get("tasks", [])
        if not isinstance(raw_tasks, list):
            return _fallback_plan(prompt)

        tasks: list[dict] = []
        for i, item in enumerate(raw_tasks[:MAX_AGENTS], start=1):
            if not isinstance(item, dict):
                continue
            task_text = str(item.get("task", "")).strip()
            if not task_text:
                continue
            task_type = str(item.get("type", "general")).lower()
            if task_type not in {"retrieval", "general"}:
                task_type = "general"
            tasks.append({
                "name": str(item.get("name") or f"worker_{i}"),
                "role": str(item.get("role") or "General assistant"),
                "type": task_type,
                "task": task_text,
            })

        if not tasks:
            return _fallback_plan(prompt)

        complexity = str(data.get("complexity", "moderate")).lower()
        if complexity not in {"simple", "moderate", "complex"}:
            complexity = "moderate"
        if complexity == "simple":
            tasks = tasks[:1]

        # ── Safety net ────────────────────────────────────────────────────
        # If the prompt needs GitHub and no publisher task exists, inject one.
        prompt_lower = prompt.lower()
        needs_github = any(w in prompt_lower for w in (
            "github", "repo", "repository", "push", "upload", "deploy"
        ))

        has_publisher = any(
            "publisher" in t["role"].lower()
            or "push" in t["task"].lower()
            or "github_push" in t["task"].lower()
            or "push all" in t["task"].lower()
            for t in tasks
        )

        if needs_github and not has_publisher and len(tasks) < MAX_AGENTS:
            repo_name = _extract_repo_name(prompt, tasks)
            tasks.append(_make_publisher_task(len(tasks) + 1, repo_name, prompt))
            if complexity == "simple":
                complexity = "moderate"
            logger.info("[planner] Injected GitHub Publisher task")

        logger.info(
            "[planner] Plan: complexity=%s tasks=%s",
            complexity, [(t["name"], t["role"]) for t in tasks],
        )
        return {"complexity": complexity, "tasks": tasks}

    except Exception as exc:
        logger.exception("Planning failed: %s", exc)
        fb = _fallback_plan(prompt)
        fb["planning_error"] = f"{type(exc).__name__}: {exc}"
        return fb
